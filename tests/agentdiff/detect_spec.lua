local H = require("helpers")

local repo = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h:h")

---Run a second headless Neovim with agentdiff on the same project and store,
---which opens `rel`, replaces its first line and writes it.
local function second_instance_writes(rel, line)
  local script = H.state .. "/second.lua"
  H.write_abs(
    script,
    ([[
package.path = %q .. "/lua/?.lua;" .. %q .. "/lua/?/init.lua;" .. package.path
vim.o.swapfile = false
local a = require("agentdiff")
a.setup({ root = %q, state_dir = %q, poll_interval = 0, auto_start = false })
a.start()
assert(a._test.wait_ready(5000))
vim.cmd.edit(%q)
vim.api.nvim_buf_set_lines(0, 0, 1, false, { %q })
vim.cmd("silent write")
a.stop()
os.exit(0)
]]):format(repo, repo, H.project, H.state .. "/agentdiff", H.path(rel), line)
  )
  local r = vim.system({ "nvim", "--headless", "-u", "NONE", "-l", script }):wait()
  assert(r.code == 0, "second instance failed: " .. (r.stderr or ""))
end

describe("detection", function()
  it("shows an edit made outside Neovim as pending (Agent edit from another tmux pane)", function()
    H.write("lua/foo.lua", "local x = 1\nreturn x\n")
    H.start()
    H.write("lua/foo.lua", "local x = 2\nreturn x\n")
    H.poll()
    eq({ "modified lua/foo.lua +1 -1 #1" }, H.pending())
  end)

  it(
    "lists files that have no buffer and shows them inline once opened (File never opened in Neovim)",
    function()
      H.write("never.lua", "a\nb\nc\n")
      H.start()
      H.write("never.lua", "a\nB\nc\n")
      H.poll()
      eq({ "modified never.lua +1 -1 #1" }, H.pending())
      local buf = H.edit("never.lua")
      local ns = require("agentdiff.render").ns
      ok(
        vim.wait(1000, function()
          return #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}) >= 2
        end, 10),
        "added-line highlight and removed virtual line are drawn"
      )
    end
  )

  it("picks changes up within 2 seconds while focused (Live update while watching)", function()
    H.write("live.lua", "one\n")
    H.start({ poll_interval = 1000, settle = 300 })
    local buf = H.edit("live.lua")
    local t0 = vim.uv.hrtime()
    H.write("live.lua", "two\n")
    local seen = vim.wait(2000, function()
      return #require("agentdiff").files() == 1
    end, 20)
    local ms = (vim.uv.hrtime() - t0) / 1e6
    ok(seen, "pending change appeared")
    ok(ms <= 2000, ("took %.0f ms"):format(ms))
    eq({ "two" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false), "the window shows the new content")
  end)

  it("reports changes made while Neovim was not running (Agent worked while Neovim was closed)", function()
    H.write("closed.lua", "x\n")
    local agentdiff = H.start()
    agentdiff.stop()
    H.write("closed.lua", "y\n")
    agentdiff.start()
    H.poll()
    eq({ "modified closed.lua +1 -1 #1" }, H.pending())
  end)

  it("waits for the settle period before attributing a change to the agent", function()
    H.write("s.lua", "a\n")
    H.start({ settle = 300 })
    H.write("s.lua", "b\n")
    H.poll(true)
    eq({}, H.pending(), "not yet confirmed")
    vim.wait(350)
    H.poll(true)
    eq({ "modified s.lua +1 -1 #1" }, H.pending())
  end)
end)

describe("claims", function()
  it("claims file changes made by a shell command run from Neovim (Shell command from Neovim)", function()
    H.write("lua/foo.lua", "a = 1\n")
    H.start()
    vim.api.nvim_feedkeys(":silent !sed -i 's/a/b/' lua/foo.lua\r", "xt", false)
    eq("b = 1\n", H.read("lua/foo.lua"))
    H.poll()
    eq({}, H.pending())
  end)

  it("settles pending agent changes before a shell command runs", function()
    H.write("x.lua", "x\n")
    H.write("y.lua", "y\n")
    H.start({ settle = 10000 })
    H.write("x.lua", "agent\n")
    vim.api.nvim_feedkeys(":silent !sed -i 's/y/Y/' y.lua\r", "xt", false)
    H.poll()
    eq({ "modified x.lua +1 -1 #1" }, H.pending())
  end)

  it("treats changes to claimed paths as the user's (Tool claims its writes)", function()
    H.write("a.lua", "return 'a'\n")
    local agentdiff = H.start()
    -- A file explorer renames a.lua to b.lua and claims both paths.
    os.rename(H.path("a.lua"), H.path("b.lua"))
    agentdiff.claim({ H.path("a.lua"), "b.lua" })
    H.poll()
    eq({}, H.pending())
  end)

  it("claims every file under a claimed directory", function()
    H.write("dir/a.lua", "a\n")
    H.write("dir/sub/b.lua", "b\n")
    local agentdiff = H.start()
    agentdiff.claim({ "dir", H.path("moved") }) -- before a directory move
    os.rename(H.path("dir"), H.path("moved"))
    agentdiff.claim({ "dir", H.path("moved") }) -- and after it
    H.poll()
    eq({}, H.pending())
  end)

  it("treats another Neovim instance's writes as the user's (Second instance)", function()
    H.write("shared.lua", "first\nsecond\n")
    H.start({ settle = 300 })
    second_instance_writes("shared.lua", "FIRST")
    eq("FIRST\nsecond\n", H.read("shared.lua"))
    H.poll(true)
    vim.wait(350)
    H.poll(true)
    eq({}, H.pending())
    -- and agent changes still show up in this instance
    H.write("shared.lua", "FIRST\nagent\n")
    H.poll()
    eq({ "modified shared.lua +1 -1 #1" }, H.pending())
  end)
end)

describe("git-guard", function()
  before_each(function()
    H.write("a.txt", "main\n")
    H.write("b.txt", "same\n")
    H.git_repo()
    H.git({ "checkout", "-q", "-b", "other" })
    H.write("a.txt", "other\n")
    H.write("c.txt", "only on other\n")
    H.git({ "add", "-A" })
    H.git({ "commit", "-q", "-m", "other" })
    H.git({ "checkout", "-q", "main" })
  end)

  it("doesn't flag files git changed on a branch switch (Branch switch)", function()
    H.start()
    H.git({ "switch", "-q", "other" })
    H.poll()
    eq({}, H.pending())
    eq("other\n", H.read("a.txt"))
    H.git({ "switch", "-q", "main" })
    H.poll()
    eq({}, H.pending())
  end)

  it("keeps pending agent changes across a commit (Commit keeps pending)", function()
    H.start()
    H.write("b.txt", "agent\n")
    H.poll()
    eq({ "modified b.txt +1 -1 #1" }, H.pending())
    H.git({ "commit", "-q", "-am", "commit the agent's work" })
    H.poll()
    eq({ "modified b.txt +1 -1 #1" }, H.pending())
  end)

  it("still flags agent edits made after a branch switch", function()
    H.start()
    H.git({ "switch", "-q", "other" })
    H.poll()
    H.write("a.txt", "agent on other\n")
    H.poll()
    eq({ "modified a.txt +1 -1 #1" }, H.pending())
  end)
end)

describe("persistence", function()
  it("keeps pending changes across a restart (Pending survives restart)", function()
    H.write("p.lua", "a\nb\n")
    local agentdiff = H.start()
    H.write("p.lua", "a\nB\n")
    H.poll()
    eq({ "modified p.lua +1 -1 #1" }, H.pending())
    agentdiff._test.reset()
    vim.cmd("silent! %bwipeout!")
    H.start()
    eq({ "modified p.lua +1 -1 #1" }, H.pending())
  end)
end)
