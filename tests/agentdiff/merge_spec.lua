local merge = require("agentdiff.merge")
local L = merge.lines

describe("merge.lines/join", function()
  it("round-trips any text, keeping the final newline as an element", function()
    for _, t in ipairs({ "", "a", "a\n", "a\nb", "a\nb\n", "\n\n", "x\r\ny\r\n" }) do
      eq(t, merge.join(L(t)))
    end
    eq({ "a", "" }, L("a\n"))
    eq({}, L(nil))
  end)
end)

describe("merge.diff", function()
  it("returns no hunks for equal content", function()
    eq({}, merge.diff(L("a\nb\n"), L("a\nb\n")))
  end)

  it("reports a changed line", function()
    local h = merge.diff(L("a\nb\nc\n"), L("a\nB\nc\n"))
    eq({ { a_lo = 1, a_hi = 2, b_lo = 1, b_hi = 2 } }, h)
    eq("changed", merge.kind(h[1]))
  end)

  it("reports added lines as an empty old range", function()
    local h = merge.diff(L("a\nc\n"), L("a\nb1\nb2\nc\n"))
    eq({ { a_lo = 1, a_hi = 1, b_lo = 1, b_hi = 3 } }, h)
    eq("added", merge.kind(h[1]))
  end)

  it("reports removed lines as an empty new range", function()
    local h = merge.diff(L("a\nb\nc\n"), L("a\nc\n"))
    eq({ { a_lo = 1, a_hi = 2, b_lo = 1, b_hi = 1 } }, h)
    eq("removed", merge.kind(h[1]))
  end)

  it("treats a created file as added from nothing and a deleted one as removed to nothing", function()
    local created = merge.diff({}, L("x\ny\n"))
    eq(1, #created)
    eq("added", merge.kind(created[1]))
    eq({ a_lo = 0, a_hi = 0, b_lo = 0, b_hi = 3 }, created[1])
    local deleted = merge.diff(L("x\ny\n"), {})
    eq("removed", merge.kind(deleted[1]))
    eq({ a_lo = 0, a_hi = 3, b_lo = 0, b_hi = 0 }, deleted[1])
  end)

  it("sees a change to the final newline", function()
    eq(1, #merge.diff(L("a\nb"), L("a\nb\n")))
  end)
end)

describe("merge.merge3", function()
  local base = L("a\nb\nc\nd\ne\n")

  it("applies disjoint changes from both sides", function()
    local m, c = merge.merge3(base, L("a\nB\nc\nd\ne\n"), L("a\nb\nc\nd\nE\n"))
    eq(L("a\nB\nc\nd\nE\n"), m)
    eq(false, c)
  end)

  it("keeps ours where both sides change the same lines", function()
    local m, c = merge.merge3(base, L("a\nB1\nc\nd\ne\n"), L("a\nB2\nc\nd\ne\n"))
    eq(L("a\nB1\nc\nd\ne\n"), m)
    eq(true, c)
  end)

  it("treats touching changes as overlapping", function()
    local m, c = merge.merge3(base, L("a\nB\nc\nd\ne\n"), L("a\nb\nC\nd\ne\n"))
    eq(L("a\nB\nc\nd\ne\n"), m)
    eq(true, c)
  end)

  it("handles an insertion at the start of the file", function()
    local m, c = merge.merge3(base, L("a\nb\nc\nD\ne\n"), L("z\na\nb\nc\nd\ne\n"))
    eq(L("z\na\nb\nc\nD\ne\n"), m)
    eq(false, c)
  end)

  it("handles an insertion at the end of the file", function()
    local m, c = merge.merge3(base, L("A\nb\nc\nd\ne\n"), L("a\nb\nc\nd\ne\nf\n"))
    eq(L("A\nb\nc\nd\ne\nf\n"), m)
    eq(false, c)
  end)

  it("keeps line offsets right after earlier insertions and deletions", function()
    local m, c = merge.merge3(base, L("a\nx1\nx2\nb\nc\nd\ne\n"), L("a\nb\nd\nE\n"))
    eq(L("a\nx1\nx2\nb\nd\nE\n"), m)
    eq(false, c)
  end)

  it("handles empty sides", function()
    eq(L("x\n"), (merge.merge3({}, {}, L("x\n"))))
    local m, c = merge.merge3({}, L("y\n"), L("x\n"))
    eq(L("y\n"), m)
    eq(true, c)
    eq({}, (merge.merge3(L("a\n"), {}, L("a\n"))))
  end)

  it("returns ours when theirs equals base", function()
    local ours = L("a\nB\nc\n")
    eq(ours, (merge.merge3(L("a\nb\nc\n"), ours, L("a\nb\nc\n"))))
  end)
end)

describe("merge helpers", function()
  it("detects binary text", function()
    ok(merge.is_binary("a\0b"))
    ok(not merge.is_binary("plain\n"))
    ok(not merge.is_binary(nil))
  end)

  it("strips and restores carriage returns of dos lines", function()
    local dos = L("a\r\nb\r\n")
    eq({ "a", "b", "" }, merge.strip_cr(dos))
    eq(dos, merge.add_cr(merge.strip_cr(dos)))
  end)
end)
