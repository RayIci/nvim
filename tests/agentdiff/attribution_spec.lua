local H = require("helpers")

describe("attribution", function()
  it(
    "shows only the agent's change when the user edits elsewhere and writes (Typing outside agent changes)",
    function()
      H.write("foo.lua", H.numbered(50))
      H.start()
      H.edit("foo.lua")
      -- agent changes line 10
      H.write("foo.lua", (H.numbered(50):gsub("l10\n", "agent10\n")))
      H.poll()
      eq({ "modified foo.lua +1 -1 #1" }, H.pending())
      -- user edits line 40 and writes
      H.change(40, 40, { "mine40" })
      H.save()
      H.poll()
      eq({ "modified foo.lua +1 -1 #1" }, H.pending())
      local f = require("agentdiff").files()[1]
      eq(9, f.hunks[1].b_lo, "the pending change is the agent's line 10")
    end
  )

  it("doesn't flag lines a formatter rewrites on save (Format on save)", function()
    H.write("fmt.lua", "a = 1\nb   =   2\nc = 3\n")
    H.start()
    local buf = H.edit("fmt.lua")
    vim.api.nvim_create_autocmd("BufWritePre", {
      buffer = buf,
      callback = function()
        vim.api.nvim_buf_set_lines(buf, 1, 2, false, { "b = 2" })
      end,
    })
    H.change(3, 3, { "c = 33" })
    H.save()
    H.poll()
    eq("a = 1\nb = 2\nc = 33\n", H.read("fmt.lua"))
    eq({}, H.pending())
  end)

  it("keeps a user tweak inside a pending change as part of it (Tweak then keep)", function()
    H.write("t.lua", "one\ntwo\nthree\n")
    local agentdiff = H.start()
    H.edit("t.lua")
    H.write("t.lua", "one\nTWO\nthree\n")
    H.poll()
    H.change(2, 2, { "TWO tweaked" })
    eq({ "modified t.lua +1 -1 #1" }, H.pending())
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    agentdiff.keep()
    eq({}, H.pending())
    H.save()
    H.poll()
    eq({}, H.pending())
    eq("one\nTWO tweaked\nthree\n", H.read("t.lua"))
  end)

  it("never keeps agent changes by writing the buffer (Write with pending changes)", function()
    H.write("w.lua", H.numbered(20))
    H.start()
    H.edit("w.lua")
    local text = H.numbered(20):gsub("l3\n", "A3\n"):gsub("l15\n", "A15\n")
    H.write("w.lua", text)
    H.poll()
    eq({ "modified w.lua +2 -2 #2" }, H.pending())
    H.save()
    H.poll()
    eq({ "modified w.lua +2 -2 #2" }, H.pending())
  end)

  it("treats unsaved typing as the user's too", function()
    H.write("u.lua", H.numbered(10))
    H.start()
    H.edit("u.lua")
    H.write("u.lua", (H.numbered(10):gsub("l2\n", "A2\n")))
    H.poll()
    H.change(8, 8, { "typed but not saved" })
    eq({ "modified u.lua +1 -1 #1" }, H.pending())
  end)
end)
